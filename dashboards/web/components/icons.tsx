export type IconName = keyof typeof PATHS;

export function Icon({ name, size = 16 }: { name: IconName; size?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {PATHS[name]}
    </svg>
  );
}

/** Icon-only button; `label` is its accessible name and the tooltip shown on hover/focus. */
export function IconButton({
  icon,
  label,
  tone,
  ...props
}: { icon: IconName; label: string; tone?: "danger" } & ButtonHTMLAttributes<HTMLButtonElement>) {
  return (
    <button
      type="button"
      {...props}
      className={`icon-btn${tone ? ` tone-${tone}` : ""}${props.className ? ` ${props.className}` : ""}`}
      aria-label={label}
      data-tip={label}
    >
      <Icon name={icon} />
    </button>
  );
}
